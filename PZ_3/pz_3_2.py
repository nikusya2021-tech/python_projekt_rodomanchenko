#вариант 28: # Дано число 1-7. Вывести название дня недели.

while True:
    try:
        n = int(input("Введите число от 1 до 7: "))
        if 1 <= n <= 7:
            break
        print("Число должно быть от 1 до 7!")
    except ValueError:
        print("Неправильно ввели!")

days = ["понедельник", "вторник", "среда", "четверг",
        "пятница", "суббота", "воскресенье"]
print(days[n - 1])