#вариант 28: Найти количество полных минут,прошедших с начала последнего часа
try:
    n=int(input("Введите количество секунд с начала суток: "))
    seconds_in_hour = n % 3600
    minutes = seconds_in_hour // 60
    print("Полных минут с начала последнего часа", minutes)
except ValueError:
    print("Ошибка: нужно ввести целое числорол.")
